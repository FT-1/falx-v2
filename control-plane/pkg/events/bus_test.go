func TestDropOnFullChannel(t *testing.T) {
	bus := NewBus()
	// Buffer of 2 events
	sub := bus.Subscribe("slow-sub", 2, TopicThreatAlert)

	// Publish 10 events into a buffer of 2 — 8 should be dropped
	for i := 0; i < 10; i++ {
		bus.Publish(ThreatAlertEvent("1.1.1.1", "scan", "medium", 0.7))
	}

	dropped := bus.DropCount()
	if dropped < 8 {
		t.Errorf("expected >= 8 drops, got %d", dropped)
	}

	// Channel should have exactly 2 events
	count := 0
	for {
		select {
		case <-sub.Ch:
			count++
		default:
			goto done
		}
	}
done:
	if count != 2 {
		t.Errorf("expected 2 events in buffer, got %d", count)
	}
}

