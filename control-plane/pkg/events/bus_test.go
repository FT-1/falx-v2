func TestConcurrentPublish(t *testing.T) {
	bus := NewBus()
	sub := bus.Subscribe("concurrent", 1024, TopicIPBlocked)

	const goroutines = 100
	var published atomic.Int64
	var wg sync.WaitGroup
	wg.Add(goroutines)

	for i := 0; i < goroutines; i++ {
		go func() {
			defer wg.Done()
			bus.Publish(IPBlockedEvent("2.2.2.2", "actor", "concurrent-test", 60))
			published.Add(1)
		}()
	}
	wg.Wait()

	// Drain channel
	received := 0
	deadline := time.Now().Add(500 * time.Millisecond)
	for time.Now().Before(deadline) {
		select {
		case <-sub.Ch:
			received++
		default:
			time.Sleep(10 * time.Millisecond)
		}
	}

	total := received + int(bus.DropCount())
	if total != goroutines {
		t.Errorf("published=%d, received=%d, dropped=%d, total=%d (should be %d)",
			published.Load(), received, bus.DropCount(), total, goroutines)
	}
}

