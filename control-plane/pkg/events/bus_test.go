func TestPublishSubscribe(t *testing.T) {
	bus := NewBus()
	sub := bus.Subscribe("test-sub", 32, TopicIPBlocked)

	bus.Publish(IPBlockedEvent("1.2.3.4", "actor", "test", 3600))

	select {
	case ev := <-sub.Ch:
		if ev.Topic != TopicIPBlocked {
			t.Errorf("wrong topic: %s", ev.Topic)
		}
		if ev.Meta["src_ip"] != "1.2.3.4" {
			t.Errorf("wrong src_ip: %s", ev.Meta["src_ip"])
		}
	case <-time.After(100 * time.Millisecond):
		t.Fatal("timeout waiting for event")
	}
}

func TestMultipleSubscribers(t *testing.T) {
	bus := NewBus()
	sub1 := bus.Subscribe("sub1", 32, TopicIPBlocked)
	sub2 := bus.Subscribe("sub2", 32, TopicIPBlocked)
	sub3 := bus.Subscribe("sub3", 32, TopicCircuitOpen) // Different topic

	bus.Publish(IPBlockedEvent("5.5.5.5", "actor", "reason", 0))

	// sub1 and sub2 should receive
	for _, sub := range []*Subscriber{sub1, sub2} {
		select {
		case ev := <-sub.Ch:
			if ev.Topic != TopicIPBlocked {
				t.Errorf("subscriber %s: wrong topic", sub.ID)
			}
		case <-time.After(100 * time.Millisecond):
			t.Errorf("subscriber %s: timeout", sub.ID)
		}
	}

	// sub3 should NOT receive (different topic)
	select {
	case ev := <-sub3.Ch:
		t.Errorf("sub3 should not receive IPBlocked, got: %s", ev.Topic)
	case <-time.After(50 * time.Millisecond):
		// Correct: no event
	}
}

